-- Builds RecipeDB.lua (every profession recipe on Forever and where it's
-- learned) from WhatsTraining's Forever ("Camelot") recipe data. WhatsTraining
-- is MIT licensed; its notice is kept in RecipeDB.lua and licenses/.
--
--   luajit tools/import-whatstraining.lua <WhatsTraining dir> > RecipeDB.lua
--
-- Per recipe (keyed by recipe/spell ID, grouped by profession ID):
--   s  required skill        c  item it creates (n: how many, or "1-3")
--   t  recipe item that teaches it (b = 1 when bind-on-pickup)
--   src  sources, one letter each: a auto-learned, t trainer, v vendor,
--        d drop, q quest, c crafted, w found in the world
--   cost  trainer cost in copper     mf  Merchant's Favor cost
--   v  vendors { area, faction }     q  quests { id, area, faction, level }
--   rep  { factionID, standing, ... }  side  recipe only for one faction
-- Factions are "A" or "H"; none means both.
local dir = assert(arg[1], "usage: import-whatstraining.lua <WhatsTraining dir>")
local FILES = { "Alchemy", "Blacksmithing", "Cooking", "Enchanting", "Engineering", "FirstAid",
    "Leatherworking", "Tailoring", "Mining" }
local CODE = { trainer = "t", vendor = "v", drop = "d", quest = "q", crafted = "c", world_object = "w" }
local FACTION = { Alliance = "A", Horde = "H" }

local ns = { L = setmetatable({}, { __index = function(_, k) return k end }) }
for _, name in ipairs(FILES) do
    assert(loadfile(dir .. "/Crafting/Recipes/Camelot/" .. name .. ".lua"))("WhatsTraining", ns)
end

local function sortedKeys(t)
    local keys = {}
    for k in pairs(t) do keys[#keys + 1] = k end
    table.sort(keys)
    return keys
end

local function q(s) return string.format("%q", s) end

local out = {}
local function emit(s) out[#out + 1] = s end

local license = io.open(dir .. "/LICENSE"):read("*a")
emit("-- Generated by tools/import-whatstraining.lua from WhatsTraining's Forever")
emit("-- recipe data (https://www.curseforge.com/wow/addons/whatstraining). Don't edit;")
emit("-- rerun the tool. Field meanings are listed at the top of that tool.")
emit("--")
emit("-- WhatsTraining's license:")
for line in (license .. "\n"):gmatch("(.-)\r?\n") do
    emit(("-- " .. line):gsub("%s+$", ""))
end
emit("local _, ns = ...")
emit("ns.RecipeDB = {")

local total = 0
for _, prof in ipairs(sortedKeys(ns.Recipes)) do
    local byId = {}
    for _, r in ipairs(ns.Recipes[prof]) do
        if not r.rank then -- profession ranks (Journeyman etc.) aren't recipes
            byId[r.spell] = r
        end
    end
    if next(byId) then
        emit(string.format("[%d] = {", prof))
        for _, id in ipairs(sortedKeys(byId)) do
            local r, f = byId[id], {}
            f[#f + 1] = "s=" .. (r.skill or 0)
            if r.creates then f[#f + 1] = "c=" .. r.creates end
            if type(r.count) == "table" then -- a range: "1-3"
                f[#f + 1] = "n=" .. q(r.count[1] .. "-" .. r.count[2])
            elseif r.count and r.count > 1 then
                f[#f + 1] = "n=" .. r.count
            end
            if r.teach then f[#f + 1] = "t=" .. r.teach end
            if r.bound then f[#f + 1] = "b=1" end
            local src = r.autoLearned and "a" or ""
            for _, s in ipairs(r.source or {}) do src = src .. (CODE[s] or "") end
            if src ~= "" then f[#f + 1] = "src=" .. q(src) end
            if r.cost then f[#f + 1] = "cost=" .. r.cost end
            if r.merchantFavor then f[#f + 1] = "mf=" .. r.merchantFavor end
            local side = r.side or r.faction
            if side and FACTION[side] then f[#f + 1] = "side=" .. q(FACTION[side]) end
            if r.vendors then
                local v = {}
                for _, vendor in ipairs(r.vendors) do
                    for _, area in ipairs(vendor.areas or { vendor.area }) do
                        v[#v + 1] = "{" .. area .. (vendor.faction and ("," .. q(FACTION[vendor.faction])) or "") .. "}"
                    end
                end
                f[#f + 1] = "v={" .. table.concat(v, ",") .. "}"
            end
            if r.quests then
                local qs = {}
                for _, quest in ipairs(r.quests) do
                    qs[#qs + 1] = string.format("{%d,%d,%s,%d}", quest.id, quest.area or 0,
                        quest.faction and q(FACTION[quest.faction]) or "nil", quest.level or 0)
                end
                f[#f + 1] = "q={" .. table.concat(qs, ",") .. "}"
            end
            if r.reputation then
                local rep = {}
                for i = 1, #r.reputation, 3 do
                    rep[#rep + 1] = r.reputation[i] .. "," .. r.reputation[i + 1]
                end
                f[#f + 1] = "rep={" .. table.concat(rep, ",") .. "}"
            end
            emit(string.format("[%d]={%s},", id, table.concat(f, ",")))
            total = total + 1
        end
        emit("},")
    end
end
emit("}")
io.write(table.concat(out, "\n"), "\n")
io.stderr:write(total .. " recipes\n")
